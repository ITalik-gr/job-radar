/**
 * Адреса сторінки в хеші: `#/companies/acme.com`.
 *
 * До цього розділ був просто станом у App, і посилання на конкретну контору не
 * існувало. Кожен перехід між розділами доводилось тягнути окремим пропом через
 * усе дерево, і таких переходів ставало більше з кожним тижнем.
 *
 * Хеш, а не History API, навмисно. Застосунок роздається як статика і з воркера,
 * і з `vite preview`, а справжні шляхи вимагають, щоб сервер на будь-який з них
 * віддавав `index.html`. Хеш працює скрізь без жодного налаштування, і ціна
 * цьому одна: зайвий символ в адресі. Свого роутера тут теж немає навмисно:
 * бібліотека заради розбору двох сегментів це та сама зайва деталь, проти якої
 * написаний розділ 11 CLAUDE.md.
 *
 * Головне, що це дає: посилання на компанію можна покласти будь-куди. У чернетку,
 * в історію листування, в телеграм-дайджест, у закладки браузера. І кнопка
 * "назад" починає працювати так, як від неї чекають.
 *
 * Тут лежить сама адреса і нічого більше: ні `window`, ні React. Саме тому її
 * перевіряє звичайний тест разом з рештою коду, а не лише клік у браузері.
 * Підписка на зміни живе окремо, у `useRoute`.
 */

/** Розбір хеша на сегменти. Експортується заради тесту: саме тут живуть крайні випадки. */
export function parse(hash: string): string[] {
  return hash
    .replace(/^#\/?/, '')
    .split('/')
    .filter(Boolean)
    .map((part) => {
      try {
        return decodeURIComponent(part);
      } catch {
        // Побитий percent-encoding в адресі це не привід показувати білий екран.
        return part;
      }
    });
}

export function href(...segments: string[]): string {
  return `#/${segments.map(encodeURIComponent).join('/')}`;
}

/** Посилання на картку компанії. Домен, бо саме по ньому її знаходить розділ Компанії. */
export function companyHref(domain: string): string {
  return href('companies', domain);
}
